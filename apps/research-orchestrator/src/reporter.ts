import type { Claim, Contribution, DispatchResult, PayloadRef, ResearchDirective, StudyReport } from './types.js';
import { getStageBSpec } from './stageb.js';
import { validityEntry, VALIDITY_LABELS } from './validity.js';

export function buildReport(
  study: { id: string; title: string; domain: string; query: string; directive: ResearchDirective },
  results: DispatchResult[],
  startedAt: string,
): Omit<StudyReport, 'researchSpec'> {
  const finishedAt = new Date().toISOString();
  const ok = results.filter(r => r.ok).length;
  const fail = results.length - ok;
  const lines: string[] = [];
  lines.push(`# ${study.title}`);
  lines.push('');
  lines.push(`**Domain:** ${study.domain} · **Query:** \`${study.query}\``);
  lines.push(`**Study:** \`${study.id}\` · **Window:** ${startedAt} → ${finishedAt}`);
  lines.push(`**Dispatched:** ${results.length} systems · **OK:** ${ok} · **Failed/offline:** ${fail}`);
  lines.push('');
  lines.push('> Single-agent orchestrator — one commander fanned the study to every registered system and aggregated below.');
  lines.push('');
  lines.push('## Per-system results');
  lines.push('');
  lines.push('| System | OK | ms | Status | Note |');
  lines.push('|---|:---:|---:|---:|---|');
  for (const r of results) {
    const body = r.body as any;
    let note = r.error ?? '';
    if (!note && body) {
      if (body.metrics) note = `papers ${body.metrics.papers_retrieved ?? body.metrics.papers_ingested ?? '?'} / hypotheses ${body.metrics.curemind_hypotheses ?? '?'}`;
      else if (Array.isArray(body) && body.length) note = `${body.length} items`;
      else if (typeof body === 'string' && body.length) note = body.slice(0, 80);
      else if (body.status) note = body.status;
    }
    if (!note) note = '—';
    lines.push(`| \`${r.systemId}\` | ${r.ok ? '✓' : '✗'} | ${r.latencyMs} | ${r.httpStatus ?? '—'} | ${note.replace(/\|/g,'·').slice(0,120)} |`);
  }
  lines.push('');
  lines.push('## What each system was asked');
  lines.push('');
  lines.push(`> Study query: "${study.query}" — routed by domain tag \`${study.domain}\`. CLI-only systems (daraxonrasib, biosim, helixforge, chemlab) returned probe hints; HTTP systems were hit live. Offline systems show ✗ — start them to include in the next report.`);
  lines.push('');
  lines.push('## Next steps');
  lines.push('');
  lines.push('- Re-run with `POST /api/study { domain, query }` for an on-demand report.');
  lines.push('- Set a cron with `POST /api/schedule { cron, domain, query, title }` (e.g. `0 2 * * *` daily 2am).');
  lines.push('- Bring offline systems online (see `GET /api/systems`) to widen coverage.');
  lines.push('');
  lines.push('---');
  lines.push(`*Generated by research-orchestrator ${finishedAt} · study ${study.id}*`);
  return {
    studyId: study.id,
    title: study.title,
    domain: study.domain,
    query: study.query,
    directive: study.directive,
    startedAt,
    finishedAt,
    systemsDispatched: results.map(r => r.systemId),
    results,
    summary: lines.join('\n'),
  };
}

// ── Paper assembly (Phase 4) ─────────────────────────────────────────────────
// The paper derives from COMBINED VERIFIED CLAIMS, not free LLM invention.
// Every statement is a claim; every claim cites its system payload hash.
// Computed and narrated evidence are kept in separate sections — a narrated
// claim must never be presented as a simulation result.

export interface PaperInputs {
  study: { id: string; title: string; domain: string; query: string; directive: ResearchDirective };
  contributions: Contribution[];
  claims: Claim[];
  payloadRefs: PayloadRef[];
  finishedAt: string;
  // Stage B systems that could not run (validation gate / offline) — surfaced
  // in the layman report so the reader knows what evidence is missing.
  dispatchProblems?: Array<{ systemId: string; reason: string }>;
  // Real-data validation scorecard (from Overlay Oncology) — cited in the
  // paper so conclusions carry concordance evidence. Optional; omitted when
  // the upstream scorecard is unreachable.
  validation?: {
    summary: string;
    fittedModel?: { fitted: boolean; fittedCIndex: number | null; heuristicCIndex: number | null };
    calibration?: { potency?: { n?: number | null; medianIc50?: number | null }; survival?: { n?: number | null; kmModelRmse?: number | null } };
  } | null;
}

function payloadCitation(claim: Claim, payloadRefs: PayloadRef[]): string {
  const ids = new Set<string>(claim.evidenceRefs.filter(r => r.type === 'system-output').map(r => r.id));
  const refs = payloadRefs.filter(p => ids.has(p.systemId) || [...ids].some(id => p.systemId.endsWith(`-${id}`)));
  if (!refs.length) return 'payload ref not archived';
  return refs.map(r => `${r.systemId} sha256:${r.sha256.slice(0, 12)} (${r.file})`).join('; ');
}

export function buildPaper(inputs: PaperInputs): string {
  const { study, claims, payloadRefs, finishedAt } = inputs;
  const verified = claims.filter(c => c.verified);
  const quarantined = claims.filter(c => !c.verified);
  const computed = verified.filter(c => c.evidenceClass === 'computed');
  const literature = verified.filter(c => c.evidenceClass === 'literature');
  const narrated = verified.filter(c => c.evidenceClass === 'narrated');
  const mixed = verified.filter(c => c.evidenceClass === 'mixed');
  const litPapers = inputs.contributions.filter(c => c.kind === 'literature' && c.papers?.length);

  const L: string[] = [];
  L.push(`# ${study.title}`);
  L.push('');
  L.push(`> **Provenance:** run \`${study.id}\` · finished ${finishedAt} · every claim below cites archived system payloads (sha256-verified).`);
  L.push(`> **Objective:** ${study.directive.objective}`);
  if (study.directive.hypothesis) L.push(`> **Standing hypothesis:** ${study.directive.hypothesis}`);
  L.push('');
  L.push('## Abstract (assembled from verified claims)');
  L.push('');
  const abs = verified.filter(c => c.kind === 'finding' || c.kind === 'hypothesis').slice(0, 8);
  L.push(abs.length ? abs.map(c => `- ${c.text} [\`${c.claimId}\`]`).join('\n') : '_No verified findings this run._');
  L.push('');
  L.push('## 1. Computed simulation results');
  L.push('');
  L.push('> ⚠️ "Computed" means the numbers came from a running engine — **not** that the engine is validated against real data. Each claim below carries a validation class (see §6). A self-consistent model is correct math with hand-tuned parameters, not a calibrated prediction.');
  L.push('');
  L.push(computed.length
    ? computed.map(c => {
        const note = c.systemId ? getStageBSpec(c.systemId)?.note : undefined;
        return `- ${c.text} [\`${c.claimId}\`, confidence ${c.confidence.toFixed(2)}]${note ? `\n  - _Engine note:_ ${note}` : ''}`;
      }).join('\n')
    : '_No computed simulation claims this run — either no Stage B system ran, or required Stage B inputs were not supplied in the study spec._');
  L.push('');
  L.push('## 2. Literature-grounded findings');
  L.push('');
  L.push(literature.length
    ? literature.map(c => `- ${c.text} [\`${c.claimId}\`]`).join('\n')
    : '_None._');
  if (litPapers.length) {
    L.push('');
    L.push('### Reference base (titles/metadata as retrieved — not full-text read)');
    for (const c of litPapers) {
      L.push(`\n**via ${c.systemId}**`);
      for (const p of c.papers!) L.push(`- [${p.published || 'n.d.'}] ${p.title} — ${p.url || p.source}`);
    }
  }
  L.push('');
  L.push('## 3. Model-generated material (NOT computed results)');
  L.push('');
  L.push(narrated.length
    ? narrated.map(c => `- ${c.text} [\`${c.claimId}\`]`).join('\n')
    : '_None — no narrated-output systems were dispatched._');
  if (mixed.length) {
    L.push('');
    L.push('## 4. Mixed/derived claims (LLM synthesis over inventory)');
    L.push('');
    L.push(mixed.map(c => `- ${c.text} [\`${c.claimId}\`, depth: ${c.evidenceDepth}]`).join('\n'));
  }
  L.push('');
  L.push('## 5. Gaps and quarantine');
  L.push('');
  const gaps = verified.filter(c => c.kind === 'gap');
  L.push(gaps.length ? gaps.map(c => `- ${c.text} [\`${c.claimId}\`]`).join('\n') : '_No explicit gap claims extracted._');
  L.push('');
  L.push(quarantined.length
    ? quarantined.map(c => `- ⚠️ QUARANTINED \`${c.claimId}\`: unresolvable refs ${c.unresolvableRefs.map(r => `${r.type}:${r.id}`).join(', ')} — ${c.text.slice(0, 160)}`).join('\n')
    : '_No claims quarantined — all evidence refs resolved._');
  L.push('');
  L.push('## 6. Methods & provenance');
  L.push('');
  L.push('Pipeline: Stage A literature ingestion → Stage B per-system simulation (inputs supplied in study spec; none invented) → Stage C synthesis → deterministic claim verification against the payload archive.');
  L.push('');
  L.push('### Validation status (how credible is each computed result?)');
  L.push('');
  L.push('| Class | Meaning |');
  L.push('|---|---|');
  for (const [k, label] of Object.entries(VALIDITY_LABELS)) L.push(`| \`${k}\` | ${label} |`);
  L.push('');
  L.push('A system marked SELF-CONSISTENT produces mathematically-correct output whose parameters are hand-tuned, not fit to real data. THEATER means the output is hardcoded/synthetic and should not be treated as a result at all. Only REAL has been validated against external data.');
  L.push('');
  L.push('| Claim | Class | Stage | System | Validation | Evidence payload (sha256, first 12 hex) |');
  L.push('|---|---|---|---|---|---|');
  for (const c of verified) {
    const v = c.validationStatus ? VALIDITY_LABELS[c.validationStatus].split(' — ')[0] : '—';
    L.push(`| \`${c.claimId}\` | ${c.evidenceClass} | ${c.stage ?? '—'} | ${c.systemId ?? '—'} | ${v} | ${payloadCitation(c, payloadRefs)} |`);
  }
  L.push('');
  if (inputs.validation) {
    L.push('## 7. Real-data validation (cited concordance evidence)');
    L.push('');
    L.push(`> ${inputs.validation.summary}`);
    if (inputs.validation.fittedModel?.fitted) {
      L.push(`- Data-fitted risk model: C-index ${inputs.validation.fittedModel.fittedCIndex} vs fixed heuristic ${inputs.validation.fittedModel.heuristicCIndex} on real TCGA-LUAD patients.`);
    }
    if (inputs.validation.calibration?.potency?.n) {
      L.push(`- Potency calibration: n=${inputs.validation.calibration.potency.n}, median IC50 ${inputs.validation.calibration.potency.medianIc50} µM (real CCLE data).`);
    }
    if (inputs.validation.calibration?.survival?.n) {
      L.push(`- Survival calibration: n=${inputs.validation.calibration.survival.n}, KM RMSE ${inputs.validation.calibration.survival.kmModelRmse} (real TCGA data).`);
    }
    L.push('');
    L.push('> These concordance numbers come from the validation scorecard (`GET /api/validation/scorecard`). The system reports them even when they are weak, so the reader can judge how much the predictions are anchored to real outcomes.');
    L.push('');
  }
  L.push(`Integrity check: \`GET /api/runs/${study.id}?verify=1\` re-hashes every archived payload and artifact against the run manifest.`);
  L.push('');
  L.push('---');
  L.push(`*Generated by research-orchestrator ${finishedAt} · study ${study.id} · ${verified.length}/${claims.length} claims verified*`);
  return L.join('\n');
}

// ── Layman paper (Phase 4b) ──────────────────────────────────────────────────
// The same verified claims, written for a non-expert reader. Deterministic
// assembly only: every statement maps to a verified claim or to dispatch
// reality (what ran, what couldn't, and why). No invention, no softening —
// narrated model opinion is explicitly separated from computed results.

const LAYMAN_SYSTEM_NOTES: Record<string, string> = {
  'overlay-oncology': 'a physics-and-chemistry cancer simulator. It treats a tumor like a digital petri dish: drug molecules diffuse through tissue (real differential-equation math), cells absorb the drug, and individual cells then live, divide, or die. It also checks its own arithmetic by tracking whether drug mass is conserved.',
  'oncoforesight': 'a treatment-outcome forecaster built on clinical-trial data. For a real patient in its database it estimates the odds of the cancer responding, staying in remission, becoming resistant, and of serious side effects, under a different treatment assignment.',
  'umoe': 'a mechanistic tumor-modeling engine. It describes tumor biology as equations — oxygen supply, drug concentration, cell populations — and returns predictions with a timeline. Its parameters can be auto-calibrated against real data before running.',
  'chemlab': 'a chemistry-lab simulator. It runs reaction kinetics: how fast a chemical reaction proceeds at a given temperature, time, and catalyst amount.',
  'attec': 'a virtual drug-screening pipeline. It scores large libraries of candidate molecules against a chosen target protein and reports which candidates look like hits.',
  'oncograph': 'an AI assistant that writes an essay-style prediction of what happens when a cancer mutation is knocked out. IMPORTANT: its output is the AI\u2019s informed opinion in narrative form — not a physics-based simulation.',
  'decon': 'a tumor-microenvironment interpreter that estimates which cell types make up a tumor sample.',
  'discourse': 'a structured debate tool where AI agents argue for and against competing hypotheses.',
};

function confidencePhrase(c: Claim): string {
  if (c.confidence >= 0.9) return 'very high — machine-computed and fully traceable to the archived run';
  if (c.confidence >= 0.7) return 'high';
  if (c.confidence >= 0.5) return 'moderate — treat as a strong hint, not a conclusion';
  return 'low — needs independent confirmation';
}

export function buildLaymanPaper(inputs: PaperInputs): string {
  const { study, claims, payloadRefs, finishedAt } = inputs;
  const verified = claims.filter(c => c.verified);
  const quarantined = claims.filter(c => !c.verified);
  const computed = verified.filter(c => c.evidenceClass === 'computed');
  const literature = verified.filter(c => c.evidenceClass === 'literature');
  const narrated = verified.filter(c => c.evidenceClass === 'narrated');
  const mixed = verified.filter(c => c.evidenceClass === 'mixed');
  const gaps = verified.filter(c => c.kind === 'gap');
  const findings = verified.filter(c => c.kind === 'finding' || c.kind === 'hypothesis');
  const litPapers = inputs.contributions.filter(c => c.kind === 'literature' && c.papers?.length);
  const problems = inputs.dispatchProblems ?? [];

  const L: string[] = [];
  L.push(`# ${study.title}`);
  L.push('');
  L.push(`**Plain-language research report** — written from the same evidence as the technical paper, minus the jargon.`);
  L.push('');
  L.push(`Every statement below comes from a research run (\`${study.id}\`, finished ${finishedAt}) whose raw computer outputs were archived and tamper-checked with cryptographic hashes. Nothing in this report was invented to fill a gap — where we don't know, it says so.`);
  L.push('');

  // 1 — the question
  L.push('## What did we want to find out?');
  L.push('');
  L.push(study.directive.objective);
  if (study.directive.hypothesis) {
    L.push('');
    L.push(`**The idea we started with:** ${study.directive.hypothesis}`);
  }
  if (study.directive.questions.length) {
    L.push('');
    L.push('**The sub-questions:**');
    for (const q of study.directive.questions) L.push(`- ${q}`);
  }
  L.push('');

  // 2 — what ran
  L.push('## How did we study it?');
  L.push('');
  L.push('The study ran in stages. First, it searched the published scientific literature and pulled in recent papers. Then it asked every relevant specialist system in the research fleet to run its own analysis of the question — real simulations and computations, each one producing archived results. Finally, all of that evidence was combined, and every conclusion was double-checked against the archived raw outputs before being allowed into this report.');
  L.push('');
  const systemIds = [...new Set(computed.map(c => c.systemId?.toString()).filter((s): s is string => Boolean(s)))];
  if (systemIds.length) {
    L.push('**The systems that produced real computed evidence:**');
    for (const sid of systemIds) {
      const note = LAYMAN_SYSTEM_NOTES[sid] ?? 'a specialist research system in the fleet.';
      L.push(`- **${sid}** is ${note}`);
    }
    L.push('');
  }
  if (problems.length) {
    L.push('**Systems that could not run this time (their evidence is missing from this report):**');
    for (const p of problems) L.push(`- **${p.systemId}** — ${p.reason}`);
    L.push('');
  }

  // 3 — the results, with numbers
  L.push('## What did the experiments show?');
  L.push('');
  if (computed.length) {
    L.push('These are the study\u2019s strongest results: numbers produced by simulation engines, not opinions. Each bullet states what was computed and how confident we are in it.');
    L.push('');
    L.push('_Honest caveat: "computed" means a real engine ran and its arithmetic checks out — it does NOT mean the engine has been proven right against real patients. The technical paper labels each result with a validation class (REAL / SELF-CONSISTENT / THEATER) so you can tell how much to trust it._');
    L.push('');
    for (const c of computed) {
      const v = c.validationStatus ? ` [validation: ${VALIDITY_LABELS[c.validationStatus].split(' — ')[0]}]` : '';
      L.push(`- ${c.text}${v}`);
      L.push(`  - *Confidence: ${confidencePhrase(c)}.*`);
    }
  } else {
    L.push('_No computed experiments ran this time, so this report has no experimental numbers in it._');
    if (problems.length) L.push(`  The reason: ${problems.map(p => p.systemId).join(', ')} could not run (see above). Supplying their required inputs and re-running the study would fill this section.`);
  }
  L.push('');

  // 4 — literature
  L.push('## What does the published science say?');
  L.push('');
  if (literature.length) {
    for (const c of literature) L.push(`- ${c.text}`);
    if (litPapers.length) {
      L.push('');
      L.push('Papers retrieved this run (titles and metadata as found — they have not each been read in full):');
      for (const c of litPapers) {
        for (const p of c.papers!.slice(0, 10)) L.push(`- "${p.title}" (${p.published || 'n.d.'}) — ${p.url || p.source}`);
      }
    }
  } else {
    L.push('_No literature-grounded claims were verified this run._');
  }
  L.push('');

  // 5 — educated guesswork
  L.push('## What is educated guesswork (not a result)?');
  L.push('');
  if (narrated.length || mixed.length) {
    L.push('The items in this section were produced by AI models reasoning in words — not by physics- or chemistry-based computation. They can be valuable for generating ideas, but they should never be quoted as experimental findings.');
    L.push('');
    for (const c of [...narrated, ...mixed]) L.push(`- ${c.text}`);
  } else {
    L.push('_Nothing — this run\u2019s conclusions all rest on computed results or published literature._');
  }
  L.push('');

  // 6 — gaps
  L.push('## What we still don\u2019t know');
  L.push('');
  if (gaps.length) {
    for (const g of gaps) L.push(`- ${g.text}`);
  } else {
    L.push('- No explicit gaps were flagged this run — which usually means the extraction step didn\u2019t surface them, not that none exist.');
  }
  if (quarantined.length) {
    L.push('');
    L.push('**Statements that failed the evidence check and were kept out of the results:**');
    for (const q of quarantined) L.push(`- ${q.text.slice(0, 200)} — rejected because its cited evidence could not be traced to anything real.`);
  }
  L.push('');

  // 7 — headline takeaways
  L.push('## The short version');
  L.push('');
  if (findings.length) {
    for (const f of findings.slice(0, 5)) L.push(`- ${f.text}`);
  } else {
    L.push('- This run did not produce verified findings — see the sections above for what is missing and why.');
  }
  L.push('');

  // 8 — how to check
  L.push('## How can I check any of this?');
  L.push('');
  L.push(`Every numbered claim in the technical version of this paper is tied to the raw computer output that produced it. Those raw outputs are stored unaltered and fingerprinted (SHA-256 hashes). You (or an auditor) can re-hash everything at any time with one request: \`GET /api/runs/${study.id}?verify=1\`. If any file has been touched since the run, the check fails loudly.`);
  L.push('');
  const payloadCount = payloadRefs.length;
  L.push(`This report draws on ${payloadCount} archived payload${payloadCount === 1 ? '' : 's'} and ${verified.length} verified claim${verified.length === 1 ? '' : 's'}${quarantined.length ? `, with ${quarantined.length} statement${quarantined.length === 1 ? '' : 's'} quarantined for failed evidence checks` : ''}.`);
  L.push('');
  L.push('---');
  L.push(`*Plain-language report generated by research-orchestrator ${finishedAt} · study ${study.id} · companion to the technical paper (${study.id} artifacts)*`);
  return L.join('\n');
}
