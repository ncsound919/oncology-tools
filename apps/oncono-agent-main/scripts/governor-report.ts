/**
 * governor-report.ts — write the governor's insights + next-batch agenda to disk,
 * so the reasoning behind the next run set is a committed artifact, not a chat log.
 *
 *   npx tsx scripts/governor-report.ts
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRunFindings, reviewRuns, THRESHOLDS } from '../server/research-governor.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', '..', '..', 'docs', 'governance');
const date = new Date().toISOString().slice(0, 10);

function main() {
  const findings = loadRunFindings();
  if (!findings.length) { console.log('[governor] no findings'); return; }
  const r = reviewRuns(findings);

  const L: string[] = [];
  L.push(`# Research governor — insights and the next run set (${date})`);
  L.push('');
  L.push('Generated by the onco agent acting as **ecosystem governor** `GET /api/onco-agent/ecosystem/govern/agenda`. Every verdict below is deterministic — no model call — so the reasoning is auditable.');
  L.push('');
  L.push('Thresholds (pre-registered, so no runtime judgement):');
  L.push('');
  L.push('| Gate | Threshold | Blocks promotion? |');
  L.push('|---|---|---|');
  L.push(`| CALIBRATION | calibrationSlope >= ${THRESHOLDS.calibrationSlopeMin} | yes |`);
  L.push(`| BALANCE | maxAbsSMD <= ${THRESHOLDS.maxAbsSmdMax} and balanceOk | yes |`);
  L.push(`| SIGNAL | discrimination >= ${THRESHOLDS.promoteAucMin} | no (a null is a finding) |`);
  L.push('| RECOVERY | per-type r >= 0.8 | no |');
  L.push(`| COVERAGE | conformal coverage >= ${THRESHOLDS.conformalCoverageMin} | no |`);
  L.push(`| LEAKAGE | canary AUC <= 0.6 / cross-cohort frac>0.95 <= ${THRESHOLDS.contaminationFracAbove95Max} | no |`);
  L.push('');
  L.push(`## Verdicts — ${r.totalFindings} lanes`);
  L.push('');
  L.push(`- **PROMOTE (${r.promoted.length}):** ${r.promoted.join(', ')}`);
  L.push(`- **REFUSE (${r.refused.length}):** ${r.refused.join(', ')}`);
  L.push('');
  for (const g of r.gated) {
    L.push(`### ${g.lane} — ${g.verdict}`);
    L.push('');
    for (const gate of g.gates) {
      L.push(`- ${gate.passed ? 'PASS' : 'FAIL'} **${gate.id}** — ${gate.name} (${gate.detail})${gate.blocksPromotion && !gate.passed ? ' — *blocks promotion*' : ''}`);
    }
    L.push('');
    L.push(`_${g.takeaway}_`);
    L.push('');
  }
  L.push('## Insights — what THESE runs teach the next ones');
  L.push('');
  r.insights.forEach((t, i) => L.push(`${i + 1}. ${t}`));
  L.push('');
  L.push('## The next run set');
  L.push('');
  if (!r.nextBatch.length) {
    L.push('_No waves derived: there were no findings to gate._');
    L.push('');
  }
  for (const w of r.nextBatch) {
    L.push(`### ${w.id} — ${w.name} (${w.kind})`);
    L.push('');
    L.push(w.rationale);
    L.push('');
    L.push('Lanes: ' + w.lanes.join(', '));
    L.push('');
  }
  L.push(`## Prior record — hand-measured observations from ${r.priorBatch.recordedFrom}`);
  L.push('');
  L.push('History, not this review. These were measured once by hand from that batch and are carried forward unchanged; only the sections above are derived from the lanes gated today.');
  L.push('');
  r.priorBatch.observations.forEach((t, i) => L.push(`${i + 1}. ${t}`));

  mkdirSync(OUT, { recursive: true });
  const p = join(OUT, `${date}-insights-and-agenda.md`);
  writeFileSync(p, L.join('\n'));
  console.log(`[governor] ${p}`);
  console.log(`[governor] ${r.totalFindings} lanes: ${r.promoted.length} promote, ${r.refused.length} refuse, ${r.nextBatch.length} waves`);
}

main();
